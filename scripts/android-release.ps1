# Build the Android APK and publish it as a GitHub release of the mobile port, which the app's
# update notice (ui/src/lib/apkupdate.ts) offers to install.
#
#   powershell -File scripts/android-release.ps1 -Version 1.4.2 [-Notes "What changed"] [-NoPublish]
#   powershell -File scripts/android-release.ps1 -Version 1.4.2 -Debuggable   (testing over USB)
#
# Builds the frontend, the Rust library (release profile) and the arm64 APK of the installed
# package, com.limusic.desktop.debug, so it installs over the app without losing its data. The
# APK is Gradle's release variant (shrunk, not debuggable); -Debuggable builds the debug one, which
# DevTools and `adb run-as` can open, and never publishes it.
#
# Signing: Android only accepts an update signed with the key of the installed APK, and Gradle signs
# this build with the debug keystore of the machine that runs it (~/.android/debug.keystore). Build
# every release on the same machine, or copy that keystore along, or the update will not install.
#
# Needs: Android SDK + NDK 28.2.13676358, JDK 21, Rust with the aarch64-linux-android target, pnpm,
# and gh (signed in) to publish.
param(
	[Parameter(Mandatory = $true)][string]$Version,
	[string]$Notes = '',
	[string]$Repo = 'Darwin2996/limusic-movil',
	[switch]$NoPublish,
	# A debuggable build, for testing over USB (DevTools, the app's files). Never published.
	[switch]$Debuggable
)
if ($Debuggable) { $NoPublish = $true }
$variant = if ($Debuggable) { 'Debug' } else { 'Release' }
$ErrorActionPreference = 'Stop'
$root = Split-Path -Parent $PSScriptRoot
Set-Location $root

if ($Version -notmatch '^\d+\.\d+\.\d+$') { throw "Version must be X.Y.Z, got '$Version'" }
$parts = $Version.Split('.') | ForEach-Object { [int]$_ }
$versionCode = $parts[0] * 1000000 + $parts[1] * 1000 + $parts[2]

# The version lives in tauri.conf.json (what the app reports, compiled into the Rust library) and in
# tauri.properties (what Android compares; Tauri's CLI writes it, and this build doesn't use the CLI).
# Written without a BOM, which Windows PowerShell's `-Encoding utf8` would add.
$utf8 = New-Object System.Text.UTF8Encoding($false)
$conf = Join-Path $root 'src-tauri\tauri.conf.json'
$json = [IO.File]::ReadAllText($conf) -replace '"version":\s*"[^"]*"', "`"version`": `"$Version`""
[IO.File]::WriteAllText($conf, $json, $utf8)
[IO.File]::WriteAllText((Join-Path $root 'src-tauri\gen\android\app\tauri.properties'),
	"// THIS IS AN AUTOGENERATED FILE. DO NOT EDIT THIS FILE DIRECTLY.`ntauri.android.versionName=$Version`ntauri.android.versionCode=$versionCode",
	$utf8)

$sdk = if ($env:ANDROID_HOME) { $env:ANDROID_HOME } else { Join-Path $env:LOCALAPPDATA 'Android\Sdk' }
$ndkBin = Join-Path $sdk 'ndk\28.2.13676358\toolchains\llvm\prebuilt\windows-x86_64\bin'
$env:ANDROID_HOME = $sdk; $env:ANDROID_SDK_ROOT = $sdk
$env:CC_aarch64_linux_android = Join-Path $ndkBin 'aarch64-linux-android28-clang.cmd'
$env:AR_aarch64_linux_android = Join-Path $ndkBin 'llvm-ar.exe'
$env:CARGO_TARGET_AARCH64_LINUX_ANDROID_LINKER = $env:CC_aarch64_linux_android
$env:TAURI_ANDROID_PROJECT_PATH = (Resolve-Path 'src-tauri\gen\android').Path
$env:WRY_ANDROID_PACKAGE = 'com.limusic.desktop'; $env:WRY_ANDROID_LIBRARY = 'app_lib'
if (-not $env:JAVA_HOME) { $env:JAVA_HOME = 'C:\Program Files\Java\jdk-21.0.10' }
$env:Path = "$env:JAVA_HOME\bin;$env:Path"

pnpm --dir ui build
if ($LASTEXITCODE -ne 0) { throw 'Frontend build failed' }

# Local copies of three Tauri plugins whose Android build scripts can't write into Cargo's cache,
# when present (.codex-tmp, never committed). The lockfile is restored after, untouched.
$patches = @()
foreach ($p in 'tauri-plugin-fs-2.5.1', 'tauri-plugin-dialog-2.7.2', 'tauri-plugin-clipboard-manager-2.3.2') {
	$dir = Join-Path $root ".codex-tmp\$p"
	if (Test-Path $dir) {
		$name = $p -replace '-\d+\.\d+\.\d+$', ''
		$patches += '--config', "patch.crates-io.$name.path='$($dir -replace '\\', '/')'"
	}
}
Copy-Item Cargo.lock "$env:TEMP\limusic-Cargo.lock" -Force
cargo build --release --manifest-path src-tauri\Cargo.toml --target aarch64-linux-android --lib `
	--features tauri/custom-protocol @patches
$cargoExit = $LASTEXITCODE
Copy-Item "$env:TEMP\limusic-Cargo.lock" Cargo.lock -Force
if ($cargoExit -ne 0) { throw 'Rust build failed' }

Copy-Item 'target\aarch64-linux-android\release\libapp_lib.so' `
	'src-tauri\gen\android\app\src\main\jniLibs\arm64-v8a\libapp_lib.so' -Force
# --rerun-tasks: an incremental package keeps the old APK's dead space (217 MB instead of 80).
.\src-tauri\gen\android\gradlew.bat -p src-tauri\gen\android ":app:assembleArm64$variant" `
	-x "rustBuildArm64$variant" --rerun-tasks --console=plain
if ($LASTEXITCODE -ne 0) { throw 'APK build failed' }

New-Item -ItemType Directory -Force dist | Out-Null
$apk = "dist\LiMusic-$Version.apk"
$out = $variant.ToLower()
Copy-Item "src-tauri\gen\android\app\build\outputs\apk\arm64\$out\app-arm64-$out.apk" $apk -Force
"APK: $apk ($([math]::Round((Get-Item $apk).Length / 1MB)) MB)"
if ($NoPublish) { return }

if (-not $Notes) { $Notes = "LiMusic para Android $Version." }
gh release create "v$Version" $apk --repo $Repo --title "LiMusic $Version" --notes $Notes
if ($LASTEXITCODE -ne 0) { throw 'Publishing the release failed' }
"Published v$Version to https://github.com/$Repo/releases"
